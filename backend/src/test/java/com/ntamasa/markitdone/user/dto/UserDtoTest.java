package com.ntamasa.markitdone.user.dto;

import static org.assertj.core.api.Assertions.assertThat;

import com.ntamasa.markitdone.user.ThemePreference;
import com.ntamasa.markitdone.user.User;
import java.util.UUID;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

class UserDtoTest {

  @Test
  @DisplayName("of copies id, email, displayName, timezone, and theme")
  void testOfCopiesUserFields() {
    UUID userId = UUID.randomUUID();
    User user =
        new User(
            "test@example.com",
            "Test User",
            "hashed_password",
            "America/New_York",
            ThemePreference.DARK);
    // Use reflection to set the ID since it's generated by JPA
    try {
      var field = User.class.getDeclaredField("id");
      field.setAccessible(true);
      field.set(user, userId);
    } catch (NoSuchFieldException | IllegalAccessException e) {
      throw new RuntimeException(e);
    }

    UserDto dto = UserDto.of(user);

    assertThat(dto.id()).isEqualTo(userId);
    assertThat(dto.email()).isEqualTo("test@example.com");
    assertThat(dto.displayName()).isEqualTo("Test User");
    assertThat(dto.timezone()).isEqualTo("America/New_York");
    assertThat(dto.themePreference()).isEqualTo(ThemePreference.DARK);
  }

  @Test
  @DisplayName("UserDto record does not have password_hash component")
  void testUserDtoDoesNotExposePasswordHash() {
    UUID userId = UUID.randomUUID();
    User user =
        new User("test@example.com", "Test User", "hashed_password", "UTC", ThemePreference.SYSTEM);
    try {
      var field = User.class.getDeclaredField("id");
      field.setAccessible(true);
      field.set(user, userId);
    } catch (NoSuchFieldException | IllegalAccessException e) {
      throw new RuntimeException(e);
    }

    UserDto dto = UserDto.of(user);

    // Verify that UserDto record fields do not include password
    assertThat(dto).hasNoNullFieldsOrProperties();
    // Check that the record components are only: id, email, displayName, timezone, themePreference
    assertThat(dto)
        .extracting("id", "email", "displayName", "timezone", "themePreference")
        .doesNotContainNull();
  }
}
